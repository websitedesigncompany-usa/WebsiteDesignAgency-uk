/**
 * Region model.
 *
 * The United States is the primary market and lives at the site root (no prefix).
 * Every other country gets a two-level path: /{country}/{city}/{service-slug}/.
 *
 * `usdRate` is the number of local currency units per 1 USD, used to convert the
 * USD price book into local currencies at build time.
 */

export interface City {
  slug: string;
  name: string;
  /** State / province / emirate / county — shown for local relevance. */
  region: string;
  /** Optional metro qualifier, e.g. "Greater Houston". */
  metro?: string;
  /** Dial-free local proof point used in copy, e.g. "+1 713-555-0142". */
  phone?: string;
  /** Local business area for case-study framing. */
  population?: string;
  /** 1-3 sentence genuinely local angle used in page intro + FAQs. */
  note: string;
}

export interface Country {
  /** ISO 3166-1 alpha-2. */
  code: string;
  /** Path segment. Empty string for the USA (root). */
  slug: string;
  name: string;
  /** "United Kingdom", "United Arab Emirates" — used in <title> and H1s. */
  longName: string;
  adjective: string;
  currency: string;
  symbol: string;
  usdRate: number;
  tld: string;
  language: string;
  /** Country-level localisation angle. */
  note: string;
  cities: City[];
}

