/**
 * Service catalogue.
 *
 * Every service is simultaneously:
 *   - a Service (what the client buys)
 *   - a Product/Offer (sellable, priced, checkout-able)
 *
 * That dual nature drives the schema: each service page emits both
 * `Service` and `Product` nodes plus `Offer`, so it can surface as a
 * rich product/service result, a local business, and a FAQ/AEO block.
 *
 * `primaryKeyword` is the exact-match phrase that MUST appear:
 *   - at the start of the meta title (<= 60 chars)
 *   - in the H1
 *   - in one H2 verbatim (the "exact primary H2")
 *   - in the meta description
 *   - throughout body paragraphs at 1.5–2% density
 */

export type ServiceCategory =
  | 'Web'
  | 'Development'
  | 'Branding'
  | 'Marketing'
  | 'SEO'
  | 'Content'
  | 'Video'
  | 'Growth';

export interface Faq {
  q: string;
  a: string;
}

export interface Service {
  /** URL segment. Home page uses '' (root) for website-design-services. */
  slug: string;
  /** Human name, e.g. "Logo Design". */
  name: string;
  /** Exact-match primary keyword, e.g. "Logo Design Services". */
  primaryKeyword: string;
  category: ServiceCategory;
  /** Short label for nav/cards. */
  nav: string;
  /** 1-line used in cards and lists. */
  tagline: string;
  /** 2–3 sentence description. */
  summary: string;
  /** 4–8 concrete deliverables, phrased as outcomes. */
  deliverables: string[];
  /** Package set key. See packages.ts */
  packageSet: 'standard' | 'seo' | 'ppc';
  /** Icon key resolved in the UI. */
  icon: string;
  /** Accent hue used for the page\'s visual theme. */
  hue: number;
  /** How long a typical engagement takes. */
  timeline: string;
  /** Starting price in USD (before regional conversion). */
  fromPrice: number;
  /** Service-specific FAQs appended to the generated set. */
  faqs: Faq[];
  /** Slugs of related services linked in-page. */
  related: string[];
  /** Industries this service converts best for. */
  industries: string[];
  /** Long-tail variants used for internal linking and blog generation. */
  longTails: string[];
  /** Rendered as the free-offer block on the page. */
  auditOffer?: { title: string; body: string; bullets: string[] };
  /** Hide the main "packages" section (used by services with bespoke pricing). */
  hidePackages?: boolean;
}

const faq = (q: string, a: string): Faq => ({ q, a });

